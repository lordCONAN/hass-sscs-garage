"""Reference token implementation, identical to the Bleak script that moved the real shutter.

Prints test vectors (random keys and challenges, never a real key) as C++ initialisers.
"""

from hashlib import sha256
import os
import sys


def make_token20(key32: bytes, pkt20: bytes, passcode: int) -> bytes:
    chal16 = pkt20[:16]
    flags = int.from_bytes(pkt20[16:20], "little")
    d = sha256(key32 + chal16).digest()
    core16 = bytes(a ^ b for a, b in zip(d[:16], d[16:]))
    if passcode == -1:
        tail = 0xFFFFFFFF
    else:
        p = passcode & 0xFFFFFFFF
        if flags & 1:
            t = int.from_bytes(sha256(chal16 + p.to_bytes(4, "little")).digest()[:4], "little")
            tail = 0xFFFFFFFE if t == 0xFFFFFFFF else t
        else:
            tail = p
    return core16 + tail.to_bytes(4, "little")


def c_bytes(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


def main() -> None:
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1234
    import random

    rng = random.Random(seed)
    cases = []
    # Fixed tail from the 2025 capture plus random ones; passcode modes covered.
    for i in range(12):
        key = bytes(rng.randrange(256) for _ in range(32))
        chal = bytes(rng.randrange(256) for _ in range(16))
        flags = [bytes.fromhex("12100900"), bytes.fromhex("13100900")][i % 2]
        passcode = [-1, -1, 12345678, 87654321, 0, 0xFFFFFFFF][i % 6]
        pkt = chal + flags
        cases.append((key, pkt, passcode, make_token20(key, pkt, passcode)))

    print("// Generated by tests/reference.py — random keys only.")
    print("struct Vector { uint8_t key[32]; uint8_t packet[20]; int64_t passcode; uint8_t token[20]; };")
    print("static const Vector VECTORS[] = {")
    for key, pkt, pc, tok in cases:
        print(f"  {{{c_bytes(key)}, {c_bytes(pkt)}, {pc}LL, {c_bytes(tok)}}},")
    print("};")


if __name__ == "__main__":
    main()
